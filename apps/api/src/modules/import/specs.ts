/**
 * Per-entity import definitions.
 *
 * Column aliases are generous on purpose: real exports from Ahrefs, Semrush,
 * BuzzStream and hand-maintained spreadsheets use every variation of "Domain
 * Rating" imaginable. Rejecting a file because the header said "DR" instead of
 * "domain_rating" is a support ticket, not a validation rule.
 */

const domainCol: ImportColumn = {
  field: "domain",
  aliases: ["domain", "website", "site", "url", "websiteurl", "domainname", "rootdomain"],
  required: true,
  example: "example.com",
};

/** A numeric column accepting every common spelling of its header. */
function numericCol(field: string, aliases: string[], example: string, description: string): ImportColumn {
  return { field, aliases: aliases.map((a) => a.toLowerCase().replace(/[\s_\-()]/g, "")), example, description };
}

